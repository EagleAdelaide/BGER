#!/usr/bin/env python3
"""Generate the OSLD data table and in-text macros from the technical check of
the received release (data/osld_release_summary.json). Standard library only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
r = json.loads((ROOT / "data" / "osld_release_summary.json").read_text())
assert r["status"] == "TECHNICAL_CHECKS_PASS"
assert r["identity_overlap"] == {"train&val": 0, "train&test": 0, "val&test": 0}
ca, ps, geo = r["cohort_accounting"], r["protocol_sets"], r["train_target_geometry"]


def n(x):
    return f"{x:,}".replace(",", "{,}")


rows = []
for s, name in (("train", "Train"), ("val", "Val (dev)"), ("test", "Test")):
    c = ca[s]
    rows.append(f"{name} & {n(r['annotation_entries'][s])} & {n(c.get('included_single_logo', 0))} & "
                f"{n(r['cohort_identities'][s])} & {n(c.get('multiple_boxes', 0))} & "
                f"{n(c.get('single_box_unlabeled', 0))} & {n(c.get('no_logo', 0))} & {n(c.get('invalid_coordinates', 0))}")
table = [
    "% AUTO-GENERATED by scripts/make_osld_tables.py from data/osld_release_summary.json",
    r"\begin{table}[t]", r"\centering\footnotesize\setlength{\tabcolsep}{2.4pt}",
    r"\caption{OSLD release as received and the annotated single-logo cohort. Columns: annotated product images; "
    r"cohort images and logo identities; exclusions (more than one box; one unlabeled box; no logo; box outside the image). "
    r"Logo identities are disjoint across splits. Galleries: development "
    + n(ps["dev_gallery"]["images"]) + r" templates of " + n(ps["dev_gallery"]["identities"])
    + r" train/val identities; test " + n(ps["gallery"]["images"]) + r" templates of "
    + n(ps["gallery"]["identities"]) + r" identities.}",
    r"\label{tab:osld}", r"\begin{tabular}{lrrrrrrr}", r"\toprule",
    r"Split & Images & Cohort & IDs & Multi & Unlab. & None & Invalid \\", r"\midrule",
    *[x + r" \\" for x in rows], r"\bottomrule", r"\end{tabular}", r"\end{table}"]
(ROOT / "tables" / "osld_data.tex").write_text("\n".join(table) + "\n")

pct = lambda x: f"{100 * x:.1f}"
macros = {
    "osldProducts": n(r["release_files"]["product_images"]),
    "osldTemplates": n(r["gallery"]["canonical_images_decodable"]),
    "osldIdentities": n(r["gallery"]["identities"]),
    "osldTrainImages": n(ps["train"]["images"]),
    "osldTrainBoxed": n(ps["train"]["with_box"]),
    "osldTrainTemplates": n(ps["train"]["images"] - ps["train"]["with_box"]),
    "osldTrainIds": n(r["training_label_count"]),
    "osldDevQueries": n(ps["dev_query"]["images"]),
    "osldTestQueries": n(ps["query"]["images"]),
    "osldTestIds": n(ps["query"]["identities"]),
    "osldDistractorIds": n(r["gallery_identities_not_in_any_split"]),
    "osldZeroOld": pct(geo["zero_target_rate_old_avgpool_gt_half"]),
    "osldZeroNew": pct(geo["zero_target_rate_any_overlap"]),
    "osldAreaMedian": pct(geo["box_area_fraction_quantiles"]["50"]),
    "osldAreaLow": pct(geo["box_area_fraction_quantiles"]["5"]),
    "osldAreaHigh": pct(geo["box_area_fraction_quantiles"]["95"]),
    "osldOccOld": pct(geo["grid_occupancy_old_quantiles"]["50"]),
    "osldOccNew": pct(geo["grid_occupancy_new_quantiles"]["50"]),
    "osldRandTest": f"{r['random_retrieval_reference']['test']['random_R@1_reference']:.1e}".replace("e-0", "\\times10^{-") + "}",
    "osldExactCross": str(r["cross_split_exact_product_duplicates_n"]),
}
text = ["% AUTO-GENERATED by scripts/make_osld_tables.py; do not edit by hand."]
text += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in sorted(macros.items())]
(ROOT / "tables" / "osld_numbers.tex").write_text("\n".join(text) + "\n")
print("OSLD table and", len(macros), "macros written")
