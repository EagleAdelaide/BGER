#!/usr/bin/env python3
"""Generate every CUB table and in-text number of the manuscript from the
per-run EV-R101 records in ../data. Standard library only; no inference.

Keys are (method, lambda, seed); rows are never selected by position.
Outputs: ../tables/*.tex and ../tables/numbers.tex (LaTeX macros).
"""
import csv
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA, OUT = ROOT / "data", ROOT / "tables"
OUT.mkdir(exist_ok=True)

rows = list(csv.DictReader((DATA / "cub_ev_r101_rows.csv").open()))
by = {(r["method"], float(r["lambda_value"]), int(r["seed"])): r for r in rows}
assert len(by) == len(rows) == 25, "expected 25 unique EV-R101 runs"
assert {r["study_generation"] for r in rows} == {"EV-R101-matched"}
assert {r["N"] for r in rows} == {"5794"}

NAMES = {"ce": "CE", "bger": "BGER", "aux": "Aux-BCE",
         "residual": "Residual-BCE", "cam_bce": "CAM-BCE"}
MAIN = [("ce", 2.0), ("aux", 2.0), ("residual", 2.0), ("bger", 2.0),
        ("cam_bce", 0.5), ("cam_bce", 2.0)]
SEEDS = (0, 1, 2)


def val(m, lam, s, key):
    return float(by[(m, lam, s)][key])


def mean_sd(m, lam, key):
    xs = [val(m, lam, s, key) for s in SEEDS]
    return statistics.mean(xs), statistics.stdev(xs)


def lam_text(m, lam):
    return "---" if m == "ce" else f"{lam:g}"


def write_table(name, caption, label, spec, head, lines, star=False):
    env = "table*" if star else "table"
    body = [rf"\begin{{{env}}}[t]", r"\centering\small\setlength{\tabcolsep}{4pt}",
            rf"\caption{{{caption}}}", rf"\label{{{label}}}",
            rf"\begin{{tabular}}{{{spec}}}", r"\toprule", head + r" \\", r"\midrule"]
    body += [ln + r" \\" for ln in lines]
    body += [r"\bottomrule", r"\end{tabular}", rf"\end{{{env}}}"]
    (OUT / f"{name}.tex").write_text(
        "% AUTO-GENERATED by scripts/make_tables.py from data/cub_ev_r101_rows.csv\n"
        + "\n".join(body) + "\n")


# ---- Table: six three-seed configurations --------------------------------
lines = []
for m, lam in MAIN:
    a, asd = mean_sd(m, lam, "Acc")
    v, vsd = mean_sd(m, lam, "V2")
    lines.append(f"{NAMES[m]} & {lam_text(m, lam)} & ${a:.4f}\\pm{asd:.4f}$ & "
                 f"${v:.4f}\\pm{vsd:.4f}$")
write_table(
    "main_results",
    r"CUB-200-2011, all six three-seed configurations of the matched generation "
    r"(mean $\pm$ sample SD over seeds 0--2; full test set, $N{=}5{,}794$; "
    r"predicted-class Grad-CAM; MaxBoxAccV2 over 101 thresholds). CAM-BCE "
    r"$\lambda{=}.5$ was added after the test frontier had been inspected "
    r"(post-hoc operating point).",
    "tab:main", "lrcc", r"Method & $\lambda$ & Accuracy & MaxBoxAccV2", lines)

# ---- Table: paired per-seed differences (percentage points) --------------
def diff(a, b, s, key):
    return 100 * (val(*a, s, key) - val(*b, s, key))


PAIRS = [(("bger", 2.0), ("ce", 2.0), "BGER $-$ CE"),
         (("bger", 2.0), ("aux", 2.0), "BGER $-$ Aux-BCE"),
         (("bger", 2.0), ("cam_bce", 0.5), r"BGER $-$ CAM-BCE$_{.5}$"),
         (("bger", 2.0), ("cam_bce", 2.0), r"BGER $-$ CAM-BCE$_{2}$")]
lines = []
for a, b, label in PAIRS:
    acc = "/".join(f"{diff(a, b, s, 'Acc'):+.2f}" for s in SEEDS)
    v2 = "/".join(f"{diff(a, b, s, 'V2'):+.2f}" for s in SEEDS)
    lines.append(f"{label} & {acc} & {v2}")
write_table(
    "paired",
    r"Same-seed differences in percentage points (seeds 0/1/2; shared "
    r"initialization within each seed). Separately trained systems: these are "
    r"comparisons between systems, not additive causal shares.",
    "tab:paired", "lcc", r"Contrast & $\Delta$Accuracy (pp) & $\Delta$MaxBoxAccV2 (pp)",
    lines)

# ---- Appendix: complete seed-0 grid ---------------------------------------
lines = []
for m in ("ce", "aux", "residual", "bger", "cam_bce"):
    for lam in ((2.0,) if m == "ce" else (0.125, 0.5, 2.0)):
        r = by[(m, lam, 0)]
        lines.append(f"{NAMES[m]} & {lam_text(m, lam)} & {float(r['Acc']):.4f} & "
                     f"{float(r['V2']):.4f} & {float(r['EIB']):.4f} & {float(r['PG']):.4f}")
write_table(
    "grid",
    r"Complete existing seed-0 coefficient grid of the matched generation "
    r"(full CUB test). Observed models only; no further weights were trained.",
    "tab:grid", "lrcccc", r"Arm & $\lambda$ & Acc. & V2 & EIB & PG", lines)

# ---- Appendix: all three-seed runs ----------------------------------------
lines = []
for m, lam in MAIN:
    for s in SEEDS:
        r = by[(m, lam, s)]
        lines.append(f"{NAMES[m]} & {lam_text(m, lam)} & {s} & {float(r['Acc']):.4f} & "
                     f"{float(r['V2']):.4f} & {float(r['EIB']):.4f} & {float(r['PG']):.4f}")
write_table(
    "all_seeds",
    r"All three-seed runs (full CUB test). With Table~\ref{tab:grid} this covers "
    r"all 25 saved runs of the generation.",
    "tab:seeds", "lrccccc", r"Method & $\lambda$ & Seed & Acc. & V2 & EIB & PG", lines)

# ---- Appendix: detach observations ----------------------------------------
det = json.loads((DATA / "detach_numerics.json").read_text())
lines = []
for r in sorted(det, key=lambda x: x["seed"]):
    mant, exp = f"{r['detached_head_weight_map_max_error']:.2e}".split("e")
    lines.append(f"{r['seed']} & {r['standard_V2']:.4f} & {r['detached_V2']:.4f} & "
                 f"${mant}\\times10^{{{int(exp)}}}$ & {r['detach_forward_max_error']:g}")
write_table(
    "detach",
    r"Gate-gradient detachment on the three BGER checkpoints (full CUB test). "
    r"Max map diff.\ compares normalized detached and head-weight maps; "
    r"forward error is the maximum absolute logit change.",
    "tab:detach", "lcccc", r"Seed & Std.\ V2 & Det.\ V2 & Max map diff. & Fwd.\ err.", lines)

# ---- In-text macros --------------------------------------------------------
macros = {}


def put(name, value):
    macros[name] = value


for m, lam in MAIN:
    tag = NAMES[m].replace("-", "").replace("BCE", "Bce") + ("Half" if lam == 0.5 else "")
    a, _ = mean_sd(m, lam, "Acc")
    v, _ = mean_sd(m, lam, "V2")
    put(f"acc{tag}", f"{a:.3f}")
    put(f"vtwo{tag}", f"{v:.3f}")


def mdiff(a, b, key):
    return statistics.mean(diff(a, b, s, key) for s in SEEDS)


put("gainBgerCe", f"{mdiff(('bger', 2.0), ('ce', 2.0), 'V2'):.2f}")
put("accBgerCe", f"{mdiff(('bger', 2.0), ('ce', 2.0), 'Acc'):+.2f}")
put("gainAuxCe", f"{mdiff(('aux', 2.0), ('ce', 2.0), 'V2'):.2f}")
put("gainBgerAux", f"{mdiff(('bger', 2.0), ('aux', 2.0), 'V2'):.2f}")
put("seedsBgerAux", "/".join(f"{diff(('bger', 2.0), ('aux', 2.0), s, 'V2'):+.2f}" for s in SEEDS))
put("gainCamTwoBger", f"{-mdiff(('bger', 2.0), ('cam_bce', 2.0), 'V2'):.2f}")
put("accCamTwoBger", f"{-mdiff(('bger', 2.0), ('cam_bce', 2.0), 'Acc'):+.2f}")
put("accCamTwoCe", f"{mdiff(('cam_bce', 2.0), ('ce', 2.0), 'Acc'):+.2f}")
put("gainBgerCamHalf", f"{mdiff(('bger', 2.0), ('cam_bce', 0.5), 'V2'):+.2f}")
put("accBgerCamHalf", f"{mdiff(('bger', 2.0), ('cam_bce', 0.5), 'Acc'):+.2f}")
put("seedsBgerCamHalf", "/".join(f"{diff(('bger', 2.0), ('cam_bce', 0.5), s, 'V2'):+.2f}" for s in SEEDS))
put("vtwoResidual", f"{mean_sd('residual', 2.0, 'V2')[0]:.3f}")
put("detStd", f"{statistics.mean(r['standard_V2'] for r in det):.3f}")
put("detDet", f"{statistics.mean(r['detached_V2'] for r in det):.3f}")
mx = max(r["detached_head_weight_map_max_error"] for r in det)
mant, exp = f"{mx:.1e}".split("e")
put("detMapMax", f"${mant}\\times10^{{{int(exp)}}}$")
boot = json.loads((DATA / "B1_existing_image_bootstrap.json").read_text())
put("bootCIs", ", ".join(
    f"$[{boot[f'seed{s}']['dV2_ci'][0]:.4f},{boot[f'seed{s}']['dV2_ci'][1]:.4f}]$" for s in SEEDS))

text = ["% AUTO-GENERATED by scripts/make_tables.py; do not edit by hand."]
text += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in sorted(macros.items())]
(OUT / "numbers.tex").write_text("\n".join(text) + "\n")
print(f"tables + {len(macros)} macros written from {len(rows)} keyed runs")
